def _rfc822(date_str):
    """Turn an ISO-ish date into an RSS pubDate, or '' when unparseable."""
    for fmt in ('%Y-%m-%d', '%Y-%m', '%Y'):
        try:
            when = datetime.datetime.strptime(str(date_str or ''), fmt)
        except ValueError:
            continue
        return when.strftime('%a, %d %b %Y 00:00:00 +0000')
    return ''


def _iso_date(date_str):
    """Turn an ISO-ish date into an RFC 3339 timestamp, or '' when unparseable."""
    for fmt in ('%Y-%m-%d', '%Y-%m', '%Y'):
        try:
            when = datetime.datetime.strptime(str(date_str or ''), fmt)
        except ValueError:
            continue
        return when.strftime('%Y-%m-%dT00:00:00Z')
    return ''


