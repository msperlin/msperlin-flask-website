def _related_packages_for_publication(publication):
    """Find R and Python packages related to a publication's title or abstract."""
    haystack = f"{publication.get('title', '')} {publication.get('abstract', '')}".lower()
    related = []
    for folder, ecosystem, field in (('code/r', 'R (CRAN)', 'title'),
                                     ('code/python', 'Python (PyPI)', 'name')):
        for pkg in load_data_from_folder(folder):
            name = (pkg.get(field) or '').strip()
            if len(name) < 3:
                continue
            base_name = name.rstrip('0123456789').lower()
            hints = _PACKAGE_TOPIC_HINTS.get(name, ())
            matched = (
                bool(re.search(rf'\b{re.escape(name.lower())}\b', haystack))
                or (len(base_name) >= 5 and bool(re.search(rf'\b{re.escape(base_name)}\b', haystack)))
                or any(hint in haystack for hint in hints)
            )
            if matched:
                related.append({
                    'name': name,
                    'ecosystem': ecosystem,
                    'description': pkg.get('description', ''),
                    'url': pkg.get('link') or pkg.get('github_link') or (
                        url_for('code_r') if folder == 'code/r' else url_for('code_python')
                    ),
                })
    return related


_STOPWORDS = {
    'the', 'and', 'for', 'with', 'from', 'that', 'this', 'using', 'based',
    'analysis', 'study', 'paper', 'market', 'markets', 'data', 'evidence',
    'brazilian', 'brazil', 'uma', 'para', 'com', 'dos', 'das', 'nos', 'nas',
    'mercado', 'brasil', 'brasileiro', 'dados', 'sobre', 'entre', 'como',
}


def _keywords(text):
    words = re.findall(r'[a-z]{4,}', (text or '').lower())
    return {w for w in words if w not in _STOPWORDS}


def _related_publications(target, limit=3):
    """Return up to `limit` related publications ranked by topic & journal overlap."""
    target_kw = _keywords(f"{target.get('title', '')} {target.get('abstract', '')}")
    target_journal = (target.get('journal') or target.get('publication') or '').strip().lower()
    scored = []
    for candidate in get_publications():
        if candidate.get('slug') == target.get('slug'):
            continue
        cand_kw = _keywords(f"{candidate.get('title', '')} {candidate.get('abstract', '')}")
        overlap = len(target_kw & cand_kw)
        same_journal = 2 if (target_journal and (candidate.get('journal') or '').strip().lower() == target_journal) else 0
        score = overlap + same_journal
        if score > 0:
            scored.append((score, int(candidate.get('year') or 0), candidate))
    scored.sort(key=lambda item: (item[0], item[1]), reverse=True)
    return [item[2] for item in scored[:limit]]


def _match_publication_by_link(link):
    """Find a local publication whose DOI or URL matches `link`."""
    if not link:
        return None
    target_doi = _doi_from_link(link).lower()
    target_url = link.strip().rstrip('/').lower()
    for pub in get_publications():
        pub_doi = (pub.get('doi') or '').lower()
        pub_url = (pub.get('link') or '').strip().rstrip('/').lower()
        if (target_doi and pub_doi and target_doi == pub_doi) or (target_url and pub_url == target_url):
            return pub
    return None


_AWARD_PAPER_HINTS = {
    'the effects of the introduction of market makers in the brazilian equity market':
        '2013-rbfin-os-efeitos-da-introducao',
    'the researchers, the publications and the journals of finance in brazil':
        '2015-rbfin-os-pesquisadores-as-publ',
}


def _match_publication_for_award(award):
    """Find the publication recognized by an award, if any."""
    desc = (award.get('description') or '').lower()
    if not desc:
        return None
    for hint, slug in _AWARD_PAPER_HINTS.items():
        if hint in desc:
            return get_publication(slug)
    for pub in get_publications():
        title = (pub.get('title') or '').strip().lower()
        if len(title) >= 12 and title in desc:
            return pub
    return None


def _related_slides_for_publication(publication):
    """Find presentation slides linked to `publication`."""
    related = []
    for slide in load_data_from_folder('slides'):
        matched = _match_publication_by_link(slide.get('paper_link'))
        if matched and matched.get('slug') == publication.get('slug'):
            related.append(slide)
    related.sort(key=lambda s: str(s.get('date') or s.get('year') or ''), reverse=True)
    return related


def _related_awards_for_publication(publication):
    """Find awards granted to `publication`."""
    related = []
